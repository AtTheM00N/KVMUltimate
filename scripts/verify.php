<?php
require '/wordpress/wp-load.php';
echo 'WordPress ' . $GLOBALS['wp_version'] . ' / PHP ' . PHP_VERSION . "\n";
function check($condition, $label) { if (!$condition) { echo 'FAIL ' . $label . "\n"; throw new Exception('FAIL ' . $label); } echo 'PASS ' . $label . "\n"; }
check(wp_is_block_theme(), 'Block theme active');
check(post_type_exists('kvm_project'), 'Project content model');
check(!get_post_type_object('kvm_enquiry')->show_in_rest && !get_post_type_object('kvm_enquiry')->public, 'Enquiries private');
check(count(get_posts(['post_type' => 'kvm_project'])) === 3, 'Local demo projects seeded');
check(kvm_integration_config()['gtm'] === '' && kvm_ad_slot('services') === '', 'Local integrations disabled');
check(str_contains(kvm_service_sections(['serviceCopy' => ['0_heading' => 'An editable headline']]), 'An editable headline'), 'Service copy editable');
foreach (glob('/wordpress/wp-content/plugins/konnect-site/includes/*.php') as $file) { token_get_all(file_get_contents($file), TOKEN_PARSE); }
token_get_all(file_get_contents('/wordpress/wp-content/themes/konnect/functions.php'), TOKEN_PARSE);
check(true, 'All PHP source parses');
$_SERVER['REMOTE_ADDR'] = '192.0.2.50';
$valid = ['kvm_nonce' => wp_create_nonce('kvm_enquiry'), 'name' => 'Verification Person', 'email' => 'verification@example.test', 'service' => 'Graphic design', 'brief' => 'This is a local verification enquiry for the test suite.'];
$bad = kvm_process_enquiry(array_merge($valid, ['email' => 'invalid']));
check(is_wp_error($bad) && isset($bad->get_error_data()['fields']['email']), 'Invalid email gives field error');
check(is_wp_error(kvm_process_enquiry(array_merge($valid, ['website' => 'spam']))), 'Honeypot rejects spam');
check(is_wp_error(kvm_process_enquiry(array_merge($valid, ['kvm_nonce' => 'expired']))), 'Expired nonce rejected');
check(is_wp_error(kvm_process_enquiry(array_merge($valid, ['attribution' => ['unexpected']]))), 'Malformed fields rejected');
$good = kvm_process_enquiry($valid);
check(!is_wp_error($good) && $good['success'], 'Valid enquiry stored');
$enquiries = get_posts(['post_type' => 'kvm_enquiry', 'post_status' => 'private']);
check(count($enquiries) === 1, 'Exactly one private enquiry');
check(get_post_meta($enquiries[0]->ID, '_kvm_email', true) === $valid['email'], 'Stored enquiry fields');
check(get_post_meta($enquiries[0]->ID, '_kvm_notification', true) === 'Needs attention: notification not sent', 'Missing email configuration flagged');
check(is_wp_error(kvm_process_enquiry($valid)), 'Duplicate submission rejected');
for ($i = 1; $i <= 4; $i++) kvm_process_enquiry(array_merge($valid, ['brief' => $valid['brief'] . ' #' . $i]));
$limited = kvm_process_enquiry(array_merge($valid, ['brief' => $valid['brief'] . ' sixth']));
check(is_wp_error($limited) && $limited->get_error_code() === 'rate_limit', 'Rate limit enforced');
$_SERVER['REMOTE_ADDR'] = '192.0.2.51';
update_option('kvm_notification_email', 'mail@example.test');
add_filter('pre_wp_mail', '__return_false');
$mail_failure = kvm_process_enquiry(array_merge($valid, ['brief' => $valid['brief'] . ' transport failure']));
check(!is_wp_error($mail_failure), 'Mail failure does not lose enquiry');
remove_filter('pre_wp_mail', '__return_false');
$demo_id = get_posts(['post_type' => 'kvm_project'])[0]->ID;
$GLOBALS['post'] = get_post($demo_id); setup_postdata($GLOBALS['post']);
update_post_meta($demo_id, '_kvm_results', 'UNVERIFIEDRESULT');
check(!str_contains(kvm_project_detail(), 'UNVERIFIEDRESULT'), 'Unverified results hidden');
update_post_meta($demo_id, '_kvm_results_verified', true);
$GLOBALS['post'] = get_post($demo_id); setup_postdata($GLOBALS['post']);
check(str_contains(kvm_project_detail(), 'UNVERIFIEDRESULT'), 'Approved results rendered');
wp_reset_postdata();
$request = new WP_REST_Request('POST', '/konnect/v1/enquiries');
$request->set_body_params(['kvm_nonce' => 'invalid']);
check(rest_do_request($request)->get_status() === 403, 'REST endpoint validates nonce');
check(str_contains(kvm_form(), 'admin-post.php'), 'No-JavaScript form fallback');
wp_set_current_user(0);
check(!current_user_can('read_post', $enquiries[0]->ID), 'Anonymous visitors cannot read enquiry');
wp_set_current_user(1);
check(current_user_can('read_post', $enquiries[0]->ID), 'Administrator can read enquiry');
foreach (get_posts(['post_type' => 'page', 'posts_per_page' => -1]) as $page) {
    $blocks = parse_blocks($page->post_content);
    check(count($blocks) > 0, 'Editable blocks: ' . $page->post_name);
}
check(WP_Block_Type_Registry::get_instance()->is_registered('konnect/studio-story') && WP_Block_Type_Registry::get_instance()->is_registered('konnect/story-chapter'), 'Studio native blocks registered');
$story = parse_blocks(kvm_studio_pattern());
check(count($story[0]['innerBlocks']) === 6, 'Six editable chapter blocks');
$escaped = kvm_render_story_chapter(['chapter' => 'intro', 'heading' => '<script>alert(1)</script>', 'linkUrl' => 'javascript:alert(1)']);
check(!str_contains($escaped, '<script>') && !str_contains($escaped, 'href="javascript:'), 'Edited chapter text and links escaped');
check(count(kvm_studio_projects()) === 2, 'Two local featured projects');
$draft = wp_insert_post(['post_type' => 'kvm_project', 'post_status' => 'draft', 'post_title' => 'Private draft verification']);
check(count(kvm_studio_projects([$draft])) === 0, 'Selected draft never exposed in scene');
check(kvm_render_story_chapter(['chapter' => 'unknown']) === '', 'Invalid scene chapter omitted');
check(str_contains(kvm_render_story_chapter(['chapter'=>'process','heading'=>'Listen. Make. Launch.']), '<span>Listen.</span><span>Make.</span><span>Launch.</span>'), 'Edited process heading drives visible scene copy');
check(str_contains(kvm_render_story_chapter(['chapter'=>'services','serviceCopy'=>['0_heading'=>['invalid']]]), '>Social</a>'), 'Malformed service overrides safely use defaults');
check(!str_contains(kvm_render_story_chapter(['chapter' => 'work', 'projectIds' => [$draft]]), 'Private draft verification'), 'Empty work chapter preserves private titles');
$home = get_page_by_path('home'); $about = get_page_by_path('about');
wp_update_post(['ID' => $home->ID, 'post_content' => kvm_legacy_page_content('home')]);
wp_update_post(['ID' => $about->ID, 'post_content' => '<!-- wp:paragraph --><p>Owner edited copy</p><!-- /wp:paragraph -->']);
delete_option('kvm_studio_version');
$migration = kvm_migrate_studio();
check(in_array('home', $migration['updated'], true) && in_array('about', $migration['preserved'], true), 'Migration upgrades baseline and preserves owner edits');
check(has_block('konnect/studio-story', get_post($home->ID)), 'Migration installs native studio journey');
check(count(wp_get_post_revisions($home->ID)) > 0, 'Migration saves restorable revision');
$edited_home = str_replace(wp_json_encode('KONNECT'), wp_json_encode('An owner-written “Connect” headline.'), kvm_studio_pattern());
wp_update_post(['ID' => $home->ID, 'post_content' => wp_slash($edited_home)]);
$retry = kvm_migrate_studio();
check(in_array('home', $retry['preserved'], true) && get_post($home->ID)->post_content === $edited_home, 'Partial migration retry preserves edited studio blocks');
kvm_migrate_studio(true);
check(kvm_migrate_studio()['status'] === 'already-current', 'Migration repeat is idempotent');
check(str_contains(get_post($about->ID)->post_content, 'One connected studio'), 'Explicit replacement restores redesigned about page');
wp_update_post(['ID' => $home->ID, 'post_content' => wp_slash($edited_home)]);
kvm_migrate_studio(true);
check(get_post($home->ID)->post_content === kvm_studio_pattern(), 'Explicit replacement works after version marker is current');
check(!str_contains(kvm_studio_image_block('studio', 'Studio'), 'http://'), 'Saved studio image URLs are origin-independent');
$old_image = '<!-- wp:html --><img src="http://127.0.0.1:9402/wp-content/themes/konnect/assets/studio/studio.webp"><!-- /wp:html -->';
wp_update_post(['ID' => $about->ID, 'post_content' => $old_image]);
check(in_array($about->ID, kvm_normalize_studio_urls(), true), 'Maintenance-port image URLs repaired explicitly');
check(str_contains(get_post($about->ID)->post_content, 'src="/wp-content/'), 'Repaired images use current origin');
wp_update_post(['ID' => $about->ID, 'post_content' => kvm_page_content('about')]);
$v2 = json_decode(file_get_contents('/wordpress/wp-content/plugins/konnect-site/includes/studio-defaults-v2.json'), true);
wp_update_post(['ID'=>$home->ID,'post_content'=>wp_slash($v2['home'][1])]);
delete_option('kvm_studio_version');
$upgrade=kvm_migrate_studio();
check(in_array('home',$upgrade['updated'],true) && get_post($home->ID)->post_content===kvm_studio_pattern(), 'Version 2 generated home upgrades to sculptural design');
echo "ALL PHP CHECKS PASSED\n";
